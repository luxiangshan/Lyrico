#!/usr/bin/env python3
"""Converts the Android string resources (lyrico-app/src/main/res/values*/ *.xml) into iOS
Localizable.strings (en + zh-Hans) and appends iOS-only strings from ios_strings.json.
Run after changing either source:  python3 ios/scripts/convert-strings.py"""
import json, os, re, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
IOS = os.path.dirname(HERE)
RES = os.path.join(os.path.dirname(IOS), "lyrico-app", "src", "main", "res")
OUT = os.path.join(IOS, "LyricoMod", "Resources")
LANGS = {"en": "values", "zh-Hans": "values-zh-rCN"}

def text_of(el):
    s = "".join(el.itertext())
    s = s.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    s = s.replace("\\'", "'").replace('\\"', '"').replace("\\@", "@").replace("\\?", "?")
    s = s.replace("\\n", "\n").replace("\\t", "\t")
    s = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", s)
    return s

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")

def load(folder):
    d = os.path.join(RES, folder)
    out = {}
    for f in sorted(os.listdir(d)):
        if not f.endswith(".xml"):
            continue
        try:
            root = ET.parse(os.path.join(d, f)).getroot()
        except ET.ParseError:
            continue
        for el in root.findall("string"):
            name = el.get("name")
            if name:
                out[name] = text_of(el)
    return out

extras = json.load(open(os.path.join(HERE, "ios_strings.json"), encoding="utf-8"))
en = load(LANGS["en"])
for lang, folder in LANGS.items():
    table = dict(en)  # fall back to English for untranslated keys
    if lang != "en":
        table.update(load(folder))
    for key, values in extras.items():
        table[key] = values.get(lang) or values["en"]
    path = os.path.join(OUT, f"{lang}.lproj")
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "Localizable.strings"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by ios/scripts/convert-strings.py from Android resources + ios_strings.json. */\n")
        for k in sorted(table):
            fh.write(f'"{esc(k)}" = "{esc(table[k])}";\n')
    print(lang, len(table))
